it('只有审核通过后才获得所申请的管理员权限，重复审核不会改变已定结果', async () => {
  const app = await application(requestedAdmin.uid);
  await identity(owner, 'authenticated');
  expect(
    await rpc('public.review_membership', [app.id, 'approve', '已核实实验室成员身份']),
  ).toMatchObject({ status: 'approved' });
  expect(await rpc('public.review_membership', [app.id, 'approve', '重试'])).toMatchObject({
    status: 'approved',
  });
  await expect(rpc('public.review_membership', [app.id, 'reject', '改为拒绝'])).rejects.toThrow(
    /已审核/,
  );
  await identity(requestedAdmin.uid, 'authenticated');
  expect(await rpc('public.is_admin')).toBe(true);
  const s = await rpc('public.get_snapshot');
  expect(s.profiles.find((p: any) => p.id === requestedAdmin.uid)).toMatchObject({
    role: 'admin',
    membership_status: 'approved',
  });
  expect(s.notices.filter((n: any) => n.title === '注册申请已通过')).toHaveLength(1);
});
