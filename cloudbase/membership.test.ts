async function identity(sub = 'anon', role = 'anon', jwtRole = role) {
  await db.exec('reset role');
  await db.query("select set_config('request.jwt.claims',$1,false)", [
    JSON.stringify({ sub, role: jwtRole }),
  ]);
  await db.exec(`set role ${role}`);
}
async function rpc(name: string, args: unknown[] = []) {
  return (
    await db.query<{ result: any }>(
      `select ${name}(${args.map((_, i) => `$${i + 1}`).join(',')}) as result`,
      args,
    )
  ).rows[0].result;
}
async function proof(email: string, score = 100) {
  await identity();
  const exam = await rpc('public.start_exam', [email]);
  expect(exam.questions).toHaveLength(10);
  expect(exam.questions.some((q: any) => 'answer' in q)).toBe(false);
  await identity('anon', 'postgres');
  const answers = (
    await db.query<{ questions: any[] }>(
      'select questions from private.exam_attempts where id=$1',
      [exam.id],
    )
  ).rows[0].questions;
  await identity();
  const result = await rpc('public.submit_exam', [
    exam.id,
    Object.fromEntries(
      answers.map((q, i) => [q.id, i < score / 10 ? q.answer : (q.answer + 1) % 4]),
    ),
  ]);
  await identity('anon', 'postgres');
  return result;
}
async function apply(email: string, requested_role = 'user') {
  const result = await proof(email);
  const input = {
    email,
    token: result.token,
    name: '申请人',
    student_id: 'APPLICANT',
    project: '项目',
    requested_role,
    username: 'hclab_' + createHash('sha256').update(email).digest('hex').slice(0, 40),
    role: 'super_admin',
  };
  const reservation = await rpc('private.claim_registration', [input]);
  await db.query('insert into auth.users(project,sub,username,email) values($1,$2,$3,$4)', [
    env,
    reservation.uid,
    reservation.username,
    email,
  ]);
  await rpc('private.finish_registration', [result.token]);
  return { uid: reservation.uid, token: result.token, input };
}
async function application(uid: string) {
  await identity(uid, 'authenticated');
  const s = await rpc('public.get_snapshot');
  return s.applications?.find((a: any) => a.user_id === uid);
}
