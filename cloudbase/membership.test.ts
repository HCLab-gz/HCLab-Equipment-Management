it('满分申请普通成员和管理员都进入待审核，无自动提权', async () => {
  pending = await apply('pending@example.invalid');
  requestedAdmin = await apply('pending-admin@example.invalid', 'admin');
  for (const [record, requested] of [
    [pending, 'user'],
    [requestedAdmin, 'admin'],
  ] as const) {
    const p = (
      await db.query('select role,membership_status from public.profiles where id=$1', [record.uid])
    ).rows[0];
    expect(p).toEqual({ role: 'user', membership_status: 'pending' });
    const app = await application(record.uid);
    expect(app).toMatchObject({
      requested_role: requested,
      status: 'pending',
      score: 100,
      rules_version: '2026-09-v3',
    });
    await identity('anon', 'postgres');
  }
});
